export const getSquadByPosition = () => {
  return {
    goalkeepers: squad.filter(p => p.positionCode === 'GK'),
    defenders: squad.filter(p => p.positionCode === 'DEF'),
    midfielders: squad.filter(p => p.positionCode === 'MID'),
    attackers: squad.filter(p => p.positionCode === 'ATT')
  }
}

export const getTopScorers = (limit = 5) => {
  return [...squad]
    .filter(p => p.goals > 0)
    .sort((a, b) => b.goals - a.goals)
    .slice(0, limit)
}

export const getTopAssisters = (limit = 5) => {
  return [...squad]
    .filter(p => p.assists > 0)
    .sort((a, b) => b.assists - a.assists)
    .slice(0, limit)
}
